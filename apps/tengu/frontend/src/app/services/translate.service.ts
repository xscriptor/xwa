@Injectable({
  providedIn: 'root',
})
export class TranslateService {
  private readonly storageKey = 'tengu-lang';
  readonly lang = signal<Lang>('en');

  constructor() {
    const saved = localStorage.getItem(this.storageKey) as Lang | null;
    if (saved === 'es') {
      this.lang.set('es');
    }
  }

  toggle(): void {
    const next = this.lang() === 'en' ? 'es' : 'en';
    this.lang.set(next);
    localStorage.setItem(this.storageKey, next);
  }

  t(key: string): string {
    return translations[this.lang()][key] || key;
  }

  isEn(): boolean {
    return this.lang() === 'en';
  }
}
