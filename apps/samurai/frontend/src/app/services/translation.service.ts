import { Injectable, signal } from '@angular/core';

export type SupportedLang = 'en' | 'es';

@Injectable({ providedIn: 'root' })
export class TranslationService {
  private readonly storageKey = 'samurai-lang';
  readonly currentLang = signal<SupportedLang>('en');
  private dict: Record<string, string> = {};

  constructor() {
    this.initLang();
  }

  initLang(): void {
    const stored = localStorage.getItem(this.storageKey) as SupportedLang | null;
    this.setLang(stored === 'es' ? 'es' : 'en');
  }

  translate(key: string): string {
    return this.dict[key] ?? key;
  }

  setLang(lang: SupportedLang): void {
    this.currentLang.set(lang);
    this.dict = lang === 'es' ? ES_DICT : EN_DICT;
    localStorage.setItem(this.storageKey, lang);
    document.documentElement.lang = lang;
  }

  toggleLang(): void {
    this.setLang(this.currentLang() === 'en' ? 'es' : 'en');
  }

  nextLangLabel(): string {
    return this.currentLang() === 'en' ? 'ESPAÑOL' : 'ENGLISH';
  }

  nextLangAria(): string {
    return this.currentLang() === 'en' ? 'Switch to Spanish' : 'Cambiar a Inglés';
  }
}

